VT_THERMAL = 0.02585  # kT/q at 27C

def diode_op(W, L, Iin, Vdd=5.0, case=0, temp=27):
    """OP of a single diode-connected PMOS50 forced at Iin. Returns dict."""
    d = _header("diode", case, 0, 0, temp)
    d += [f"Vdd vdd 0 {Vdd:.6g}", f"Iin nd 0 {Iin:.9g}",
          _dev("d", "nd", "nd", "vdd", "vdd", W, L, 1)]
    for p in ("vth","vdsat","gm","gds","id","vgs"):
        d.append(f".control\nop\nprint @m.xd.m0[{p}]\n.endc") if False else None
    d += [".control", "op"]
    for p in ("vth","vdsat","gm","gds","id","vgs","cgg"):
        d.append(f"print @m.xd.m0[{p}]")
    d += [".endc", ".end"]
    op = parse_op(run("\n".join(d), "diode"))["xd.m0"]
    vsg = abs(op["vgs"]); vth = abs(op["vth"]); idd = abs(op["id"])
    vov = vsg - vth
    gm_id = op["gm"]/idd
    # EKV inversion coefficient from gm/Id (n~1.3): gm/Id=1/(n Vt (sqrt(IC+.25)+.5))
    n = 1.3
    x = 1.0/(gm_id*n*VT_THERMAL)          # = sqrt(IC+.25)+.5
    IC = (max(x-0.5, 1e-6))**2 - 0.25
    return dict(W=W, L=L, vov=vov, vdsat=op["vdsat"], vsg=vsg, vth=vth,
                id=idd, gm_id=gm_id, IC=max(IC, 0.0), gds=op["gds"])


def size_W_for_vov(L, Iin, target_vov=0.20, Wmin=0.5e-6, Wmax=4e-3,
                   Vdd=5.0, case=0, temp=27, tol=2e-3):
    """Bisection on W so that Vov = |VSG|-|Vth| == target_vov.  Larger W -> lower
    Vov.  Returns (W, op_dict, clamped_bool)."""
    lo, hi = Wmin, Wmax
    op_lo = diode_op(lo, L, Iin, Vdd, case, temp)
    if op_lo["vov"] <= target_vov:
        # even Wmin overdrives too little -> clamp at Wmin (subthreshold regime)
        return lo, op_lo, True
    for _ in range(40):
        mid = (lo*hi)**0.5           # geometric bisection (W spans decades)
        op = diode_op(mid, L, Iin, Vdd, case, temp)
        if abs(op["vov"] - target_vov) < tol:
            return mid, op, False
        if op["vov"] > target_vov:   # too much overdrive -> widen
            lo = mid
        else:
            hi = mid
    return mid, op, False


def calibrate_vbias(geom, Iin, Vdd=5.0, case=0, temp=27, self_biased=False):
    """Search the wide-swing bias drop (vbias, V below Vdd) that MAXIMIZES the
    1%-compliance V_out,max while holding |gain(Vdd/2)-1| < 0.5%.  Returns vbias."""
    import numpy as _np
    best = (None, -1.0)
    for vb in _np.arange(1.5, 2.8+1e-9, 0.05):
        g = dict(geom, vbias=float(vb), Iin=Iin)
        deck, out = deck_dc("cal", "MIR_CW", g, Iin, Vdd, 0, Vdd, 0.05,
                            case=case, temp=temp)
        run(deck, "cal")
        v, i = read_wrdata(out)
        i0 = i[0]
        gmid = i[_np.argmin(abs(v-Vdd/2.0))]/Iin
        below = _np.where(i < 0.99*i0)[0]
        vmax = v[below[0]] if len(below) else v[-1]
        if abs(gmid-1.0) < 0.005 and vmax > best[1]:
            best = (float(vb), float(vmax))
    return best[0] if best[0] is not None else 2.0
